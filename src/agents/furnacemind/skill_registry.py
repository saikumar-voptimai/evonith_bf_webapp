"""Database-backed quick-skill registry for FurnaceMind.

This module is the bridge between the ``furnace_mind.skills`` SQL table and the
quick-skill buttons shown in the FurnaceMind chat UI. A database row controls the
human-facing configuration: name, symbol, active state, instruction text, and any
supporting ``.md`` context files. Python keeps ownership of execution by mapping
rows only to a small whitelist of ``SkillEngine`` handlers.

That split is deliberate. Operators can add, hide, rename, and tune prompt-based
skills from the UI/database, while the application still avoids running arbitrary
code or reading arbitrary files from values stored in SQL. If the database is
empty or unavailable, the registry falls back to the built-in skills so the chat
screen remains usable.
"""

from __future__ import annotations

import math
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from datetime import date, timezone
from pathlib import Path
from typing import Any

from furnace_data.runtime_paths import get_repo_root, runtime_path

_COPILOT_DATA_DIR = get_repo_root() / "src" / "storage" / "furnacemind"
_SLUG_RE = re.compile(r"[^a-z0-9_]+")
_SKILL_SEARCH_CONTEXT_CHARS = 6_000
_RETRIEVED_SKILL_CONTEXT_CHARS = 8_000
_SEMANTIC_SKILL_LIMIT = 2
_SEMANTIC_SKILL_MIN_SCORE = 0.42


@dataclass(frozen=True)
class SkillDefinition:
    """Normalized runtime configuration for one FurnaceMind quick skill.

    The UI and chat pipeline should not care whether a skill came from a SQL row
    or from the built-in fallback list. This dataclass gives both sources the
    same shape. ``slug`` is the stable application key used for Streamlit state
    and prompt context. ``handler`` names a whitelisted ``SkillEngine`` method
    for built-in/code-backed skills; prompt-only DB skills leave it blank and use
    ``instruction`` plus optional ``context_files`` instead.
    """

    skill_id: str
    slug: str
    name: str
    symbol: str = ""
    description: str = ""
    instruction: str = ""
    source_type: str = "built_in"
    handler: str = ""
    display_template: str = ""
    context_files: tuple[str, ...] = ()
    order: int = 1000
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def button_label(self) -> str:
        """Return the compact label displayed on the quick-skill button."""
        return f"{self.symbol} {self.name}".strip()


@dataclass(frozen=True)
class SkillExecution:
    """Prompt, display label, and extra context generated by a skill click.

    ``prompt`` becomes the queued user message, ``display`` is what the chat UI
    shows for that click, and ``skill_context`` is injected into the agent prompt
    so DB-provided instructions and uploaded skill files can guide the answer.
    """

    prompt: str
    display: str
    skill_id: str
    skill_context: str = ""


class _SafeFormatDict(dict[str, str]):
    """Dictionary used by ``str.format_map`` to preserve unknown placeholders."""

    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


