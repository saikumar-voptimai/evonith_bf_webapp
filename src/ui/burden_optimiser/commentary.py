"""Furnace commentary panel for the Burden & Fuel Optimiser page: the model call and the rendering.

Context assembly is pure and lives in ``utils/burden_engine/commentary.py``. Same rules as page 9's panel
(``ui/bmo/commentary.py``): it is on a button, never automatic (a model call costs money and seconds, and the page
reruns constantly while inputs are edited); the generated text sits below the numbers and says it is generated; and
the full context the model was given is shown, and can be downloaded, so every sentence can be audited.
"""

from __future__ import annotations

import hashlib
import logging

import streamlit as st

from utils.burden_engine.commentary import SYSTEM_PROMPT, CommentaryContext

log = logging.getLogger(__name__)


def _generate(system_prompt: str, user_prompt: str) -> str:
    """One model call through the app's LLM client. Raises on failure so the caller can report it."""

    from agents.llm.llm_client import get_llm_client

    return str(get_llm_client().generate(system_prompt, user_prompt) or "").strip()


def render_furnace_commentary(context: CommentaryContext, key: str = "bfo") -> None:
    """Commentary on the plan on screen: button, generated text, and the context it was given."""

    st.markdown("### 🧠 Furnace commentary")
    st.caption(
        "A reading of this page by the FurnaceMind model. It is given the optimiser notes (how every number is made "
        "and where it is weak), the fact register as a table, and this run: the model check, the plan, today's blend, "
        "what binds and the yard. **It is generated text, not a calculation.** Every number it quotes comes from this "
        "page; check anything you intend to act on.")
    if not context.is_usable:
        st.info("Run the optimiser first: there is no plan to comment on yet.")
        return

    digest = hashlib.sha1(context.text.encode("utf-8")).hexdigest()[:12]
    left, mid, right = st.columns([3, 1, 1], vertical_alignment="center")
    with left:
        if context.missing:
            st.caption("⚠️ Not available for this run: " + ", ".join(context.missing)
                       + ". The commentary is told so and will not guess.")
    with mid:
        st.download_button("Download context", context.text, file_name=f"bf2_optimiser_context_{digest}.md",
                           mime="text/markdown", width="stretch", key=f"{key}_ctx_dl",
                           help="The full text the model is given, to read or to use elsewhere.")
    with right:
        asked = st.button("Generate commentary", type="primary", width="stretch", key=f"{key}_commentary_go",
                          help="Sends the context to the model. Takes several seconds.")
    store = st.session_state.setdefault(f"{key}_commentary", {})
    if asked:
        with st.spinner("Reading the model check, the plan and today's blend…"):
            try:
                store[digest] = _generate(SYSTEM_PROMPT, context.text)
            except Exception as exc:  # noqa: BLE001 - never break the results page
                log.exception("Furnace commentary failed")
                st.error("Could not generate commentary: " + (str(exc).splitlines() or [""])[0][:200]
                         + "\n\nThe numbers above are unaffected; the context can still be downloaded.")
    text = store.get(digest)
    if text:
        with st.container(border=True):
            st.markdown(text)
        st.caption("Generated by a language model from the context below. It can be wrong, and it cannot see anything "
                   "that is not in that context: no burden-distribution change, maintenance or what the last shift saw.")
    elif store:
        st.caption("The inputs or the plan changed since the last commentary: generate it again for this plan.")
    with st.expander("What the model is given", expanded=False):
        st.code(context.text, language="markdown")
