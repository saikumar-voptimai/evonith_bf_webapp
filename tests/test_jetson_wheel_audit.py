def test_recipe_runs_the_makefile_commands_for_the_jetson(tmp_path: Path) -> None:
    calls = tmp_path / "calls.jsonl"
    fake = tmp_path / "fake_uv.py"
    fake.write_text(
        textwrap.dedent(f"""\
            import json, pathlib, sys
            args = sys.argv[1:]
            with open({str(calls)!r}, "a", encoding="utf-8") as fh:
                fh.write(json.dumps(args) + "\\n")
            if args == ["--version"]:
                print("uv 0.7.13 (62ed17b23 2025-06-12)")
            elif args[:1] == ["export"]:
                pathlib.Path(args[args.index("-o") + 1]).write_text("torch==2.2.2\\n", encoding="utf-8")
            elif args[:2] == ["pip", "compile"]:
                out = pathlib.Path(args[args.index("-o") + 1])
                out.write_text("torch==2.2.2\\npypika==0.48.9\\n", encoding="utf-8")
            """),
        encoding="utf-8",
    )
    resolved, version = audit.run_recipe([sys.executable, str(fake)], PLATFORM, ["pypika", "quickjs"], cwd=tmp_path)
    assert resolved == {"torch": "2.2.2", "pypika": "0.48.9"} and version == "0.7.13"
    made = [json.loads(line) for line in calls.read_text(encoding="utf-8").splitlines()]
    assert made[1] == ["lock", "--check"]
    assert made[2][:6] == ["export", "--frozen", "--no-hashes", "--no-emit-project", "--all-groups", "--quiet"]
    compile_args = made[3]
    assert compile_args[:2] == ["pip", "compile"] and "--no-deps" in compile_args
    flags = " ".join(compile_args)
    assert "--python-version 3.12 --python-platform aarch64-manylinux_2_35 --only-binary :all:" in flags
    assert "--no-binary pypika --no-binary quickjs" in flags

    failing = tmp_path / "failing_uv.py"
    failing.write_text("import sys\nprint('lock is stale', file=sys.stderr)\nsys.exit(2)\n", encoding="utf-8")
    with pytest.raises(RuntimeError, match="exit 2"):
        audit.run_recipe([sys.executable, str(failing)], PLATFORM, [], cwd=tmp_path)


def test_render_block_counts_kinds_and_lists_absent_packages() -> None:
    packages = {
        "evonith-bf-webapp": [{"name": "evonith-bf-webapp", "version": "0.1", "source": {"virtual": "."}}],
        "furnace-data": [{"name": "furnace-data", "version": "0.1", "source": {"editable": "furnace_data"}}],
        "torch": [_package("torch", "torch-2.2.2-cp312-cp312-manylinux2014_aarch64.whl", version="2.2.2")],
        "pywin32": [_package("pywin32", "pywin32-308-cp312-cp312-win_amd64.whl", sdist=False, version="308")],
        "pypika": [_package("pypika", version="0.48.9")],
    }
    block = audit.render_block(
        packages, {"torch": "2.2.2", "pypika": "0.48.9"}, TAGS, PLATFORM, ["pypika"], "0.7.13", dt.date(2026, 10, 29)
    )
    assert block.startswith(
        audit.MARK_START + "\nRecipe of `make lock-check` run by hand on 29 Oct 2026 with uv 0.7.13"
    )
    assert block.endswith(audit.MARK_END + "\n")
    assert "resolved 2 packages" in block and ": no problem." in block
    assert "| CPython 3.12 aarch64 wheel | 1 |" in block and "| source build (sdist) | 1 |" in block
    assert "no installable file" not in block
    assert "Highest glibc floor of the selected wheels: 2.17 (torch)" in block
    assert "(markers for other platforms): pywin32." in block and "this repository): furnace-data." in block
    assert "| highspy | not locked |" in block


def test_replace_block_keeps_the_rest_of_the_document() -> None:
    doc = f"head\n\n{audit.MARK_START}\nold\n{audit.MARK_END}\n\ntail\n"
    block = f"{audit.MARK_START}\nnew\n{audit.MARK_END}\n"
    once = audit.replace_block(doc, block)
    assert once == f"head\n\n{block}\ntail\n"
    assert audit.replace_block(once, block) == once
    with pytest.raises(ValueError):
        audit.replace_block("no markers\n", block)


def test_audit_covers_the_tickets_packages() -> None:
    names = {name for name, _, _ in audit.AUDIT}
    ticket = {"torch", "highspy", "psycopg2-binary", "duckdb", "chromadb", "pyarrow", "sentence-transformers", "scipy"}
    assert ticket <= names and {"pypika", "quickjs"} <= names


def test_document_table_matches_uv_lock() -> None:
    """Re-run ``python scripts/jetson_wheel_audit.py --write`` after a lock change."""
    doc = audit.DOC.read_text(encoding="utf-8")
    block = doc[doc.index(audit.MARK_START) : doc.index(audit.MARK_END)]
    rows = [line for line in block.splitlines() if line.startswith("| ") and not line.startswith("| Package |")]
    table = [r for r in rows if r.count("|") == 8]
    assert table == audit.table_rows(audit.load_lock(), TAGS)
    assert ": no problem." in block and "PROBLEM" not in block
